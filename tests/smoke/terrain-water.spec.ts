import { writeFile } from "node:fs/promises";
import { expect, test } from "./test";

test("physics wheelspin excites water without wheel rotation, stays inside its puddle and leaves the shoreline stable", async ({ page }, info) => {
  test.setTimeout(180_000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  await page.setViewportSize({ width: 960, height: 640 });
  await page.goto("/tests/smoke/pages/wet-mud.html", { waitUntil: "domcontentloaded" });
  await expect.poll(() => page.evaluate(() => Boolean((window as any).__wetMudQa?.ready)), { timeout: 120_000 }).toBe(true);
  await page.evaluate(() => (window as any).__wetMudQa.enableDynamics("low"));
  const calmProfile = await page.evaluate(() => (window as any).__wetMudQa.profile());
  const calm = await page.evaluate(() => (window as any).__wetMudQa.waveEnergy());
  await page.evaluate(() => (window as any).__wetMudQa.pumpWater(24, "traction"));
  const moving = await page.evaluate(() => (window as any).__wetMudQa.waveEnergy());
  const waves = await page.evaluate(() => (window as any).__wetMudQa.waveSamples());
  const movingProfile = await page.evaluate(() => (window as any).__wetMudQa.profile());
  await page.evaluate(() => (window as any).__wetMudQa.rippleAppearance(false));
  await page.screenshot({ path: info.outputPath("terrain-water-without-wavefronts.png") });
  const appearance = await page.evaluate(() => (window as any).__wetMudQa.rippleAppearance(true));
  expect(appearance.changed).toBeGreaterThan(100);
  expect(appearance.maxDifference).toBeGreaterThan(35);
  expect(moving).toBeGreaterThan(calm + 100);
  expect(waves.left).toBeGreaterThan(0.001);
  expect(waves.right).toBe(0);
  expect(waves.dry).toBe(0);
  expect(movingProfile.map((probe: { puddle: number }) => probe.puddle)).toEqual(calmProfile.map((probe: { puddle: number }) => probe.puddle));
  await page.screenshot({ path: info.outputPath("terrain-water-physics-slip.png") });
  await page.evaluate(() => (window as any).__wetMudQa.shiftDynamics());
  const shifted = await page.evaluate(() => (window as any).__wetMudQa.waveSamples());
  expect(Math.abs(shifted.centreX - waves.centreX)).toBeLessThan(0.13);
  expect(Math.abs(shifted.centreZ - waves.centreZ)).toBeLessThan(0.13);
  await page.evaluate(() => (window as any).__wetMudQa.pumpWater(180, false));
  const settled = await page.evaluate(() => (window as any).__wetMudQa.waveEnergy());
  expect(settled).toBeLessThan(moving * 0.3);
  await page.screenshot({ path: info.outputPath("terrain-water-physics-slip-settled.png") });
  await writeFile(info.outputPath("terrain-water-physics-slip.json"), JSON.stringify({ calm, moving, settled, waves, shifted, appearance, calmProfile, movingProfile }, null, 2));
  expect(errors).toEqual([]);
});

test("terrain water ripples respond to wheels, settle, and reflect scene objects across three quality tiers", async ({ page }, info) => {
  test.setTimeout(300_000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") errors.push(message.text()); });
  await page.setViewportSize({ width: 960, height: 640 });
  await page.goto("/tests/smoke/pages/wet-mud.html", { waitUntil: "domcontentloaded" });
  await expect.poll(() => page.evaluate(() => Boolean((window as any).__wetMudQa?.ready)), { timeout: 120_000 }).toBe(true);
  const environment = await page.evaluate(() => (window as any).__wetMudQa.skyLight());
  const medium = await page.evaluate(() => (window as any).__wetMudQa.enableDynamics("medium"));
  expect(medium.resolution).toBe(256);
  expect(medium.captures).toBeGreaterThan(0);
  const ground = await page.evaluate(() => (window as any).__wetMudQa.groundColor() as number[]);
  expect(ground[0]! - ground[2]!).toBeGreaterThan(5);
  const calm = await page.evaluate(() => (window as any).__wetMudQa.waveEnergy());
  const stirring = await page.evaluate(() => (window as any).__wetMudQa.pumpWater(12, true));
  const moving = await page.evaluate(() => (window as any).__wetMudQa.waveEnergy());
  expect(moving).toBeGreaterThan(calm + 100);
  const shifted = await page.evaluate(() => (window as any).__wetMudQa.shiftDynamics());
  expect(shifted).toBeGreaterThan(moving * 0.1);
  expect(shifted).toBeLessThan(moving * 2);
  await page.screenshot({ path: info.outputPath("terrain-water-ripples.png") });
  const settling = await page.evaluate(() => (window as any).__wetMudQa.pumpWater(180, false));
  const settled = await page.evaluate(() => (window as any).__wetMudQa.waveEnergy());
  await writeFile(info.outputPath("terrain-water-motion.json"), JSON.stringify({ calm, moving, settled, stirring, settling }, null, 2));
  expect(settled).toBeLessThan(moving * 0.3);
  await page.waitForTimeout(70);
  const red = await page.evaluate(() => (window as any).__wetMudQa.reflectionColor(true) as number[]);
  await page.waitForTimeout(70);
  const blue = await page.evaluate(() => (window as any).__wetMudQa.reflectionColor(false) as number[]);
  expect(Math.max(...red.map((v, i) => Math.abs(v - blue[i]!)))).toBeGreaterThan(15);
  await page.screenshot({ path: info.outputPath("terrain-water-planar-medium.png") });
  const capture = await page.evaluate(() => (window as any).__wetMudQa.showCapture() as number[][]);
  expect(capture.filter((pixel) => pixel[2]! - pixel[0]! > 80).length).toBeGreaterThan(capture.length * 0.9);
  await page.screenshot({ path: info.outputPath("terrain-water-capture-medium.png") });
  await page.evaluate(() => (window as any).__wetMudQa.restoreView());
  const mediumTiming = await page.evaluate(() => (window as any).__wetMudQa.benchmarkFrames(4));
  const low = await page.evaluate(() => (window as any).__wetMudQa.enableDynamics("low"));
  expect(low.groups).toBe(0); expect(low.captures).toBe(0);
  await page.waitForTimeout(70);
  const skyRed = await page.evaluate(() => (window as any).__wetMudQa.reflectionColor(true) as number[]);
  await page.waitForTimeout(70);
  const skyBlue = await page.evaluate(() => (window as any).__wetMudQa.reflectionColor(false) as number[]);
  expect(Math.max(...skyRed.map((v, i) => Math.abs(v - skyBlue[i]!)))).toBeLessThan(3);
  await page.screenshot({ path: info.outputPath("terrain-water-sky-low.png") });
  const lowTiming = await page.evaluate(() => (window as any).__wetMudQa.benchmarkFrames(4));
  const high = await page.evaluate(() => (window as any).__wetMudQa.enableDynamics("high"));
  expect(high.resolution).toBe(512); expect(high.captures).toBeGreaterThan(0);
  await page.screenshot({ path: info.outputPath("terrain-water-planar-high.png") });
  const highTiming = await page.evaluate(() => (window as any).__wetMudQa.benchmarkFrames(4));
  const depthMode = await page.evaluate(() => (window as any).__wetMudQa.reverseDepth());
  await page.waitForTimeout(70);
  const reverseRed = await page.evaluate(() => (window as any).__wetMudQa.reflectionColor(true) as number[]);
  await page.waitForTimeout(70);
  const reverseBlue = await page.evaluate(() => (window as any).__wetMudQa.reflectionColor(false) as number[]);
  expect(Math.max(...reverseRed.map((v, i) => Math.abs(v - reverseBlue[i]!)))).toBeGreaterThan(15);
  await page.screenshot({ path: info.outputPath("terrain-water-reversed-depth.png") });
  await page.evaluate(() => (window as any).__wetMudQa.tracks(0, 0.25, 1));
  const narrow = await page.evaluate(() => (window as any).__wetMudQa.enableDynamics("high"));
  expect(narrow.captures).toBeGreaterThan(0);
  await page.waitForTimeout(70);
  const narrowRed = await page.evaluate(() => (window as any).__wetMudQa.reflectionColor(true) as number[]);
  await page.waitForTimeout(70);
  const narrowBlue = await page.evaluate(() => (window as any).__wetMudQa.reflectionColor(false) as number[]);
  expect(Math.max(...narrowRed.map((v, i) => Math.abs(v - narrowBlue[i]!)))).toBeGreaterThan(10);
  await page.screenshot({ path: info.outputPath("terrain-water-narrow-25cm.png") });
  const released = await page.evaluate(() => (window as any).__wetMudQa.releaseDynamics());
  expect(released.resolution).toBe(0); expect(released.captures).toBe(0);
  expect(await page.evaluate(() => (window as any).__wetMudQa.environmentId())).toBe(environment);
  await writeFile(info.outputPath("terrain-water-metrics.json"), JSON.stringify({ calm, moving, shifted, settled, stirring, settling, medium, low, high, narrow, depthMode, mediumTiming, lowTiming, highTiming, released }, null, 2));
  expect(errors).toEqual([]);
});
